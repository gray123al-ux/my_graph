st.divider()

st.header("4. 영화별 기간 관객 TOP 10")

st.write(
    "영화별로 이 기간의 일관객을 모두 더해 "
    "관객이 가장 많았던 영화 10편을 비교합니다."
)


# ---------------------------------------------------------
# 영화별 관객 합계
# ---------------------------------------------------------

movie_total = (
    df.groupby("영화명", as_index=False)["일관객"]
    .sum()
    .rename(columns={"일관객": "관객합계"})
)


# ---------------------------------------------------------
# 10위권에 등장한 날짜 수 계산
# ---------------------------------------------------------

movie_days = (
    df.groupby("영화명")["날짜"]
    .nunique()
    .reset_index()
    .rename(columns={"날짜": "등장일수"})
)


# ---------------------------------------------------------
# 합치기
# ---------------------------------------------------------

movie_rank = pd.merge(
    movie_total,
    movie_days,
    on="영화명"
)


# ---------------------------------------------------------
# TOP 10 선정
# ---------------------------------------------------------

top10 = (
    movie_rank
    .sort_values("관객합계", ascending=False)
    .head(10)
)

# 가로 막대그래프에서 큰 값이 위로 오도록 순서 뒤집기
top10 = top10.sort_values("관객합계")


# ---------------------------------------------------------
# 가로 막대그래프
# ---------------------------------------------------------

fig4 = px.bar(
    top10,
    x="관객합계",
    y="영화명",
    orientation="h",
    text="관객합계",
    custom_data=["등장일수"],
    labels={
        "관객합계": "기간 관객 수",
        "영화명": "영화"
    }
)

fig4.update_traces(
    texttemplate="%{x:,.0f}",
    textposition="outside",
    hovertemplate=(
        "영화: %{y}"
        "<br>기간 관객 수: %{x:,.0f}명"
        "<br>10위권 등장일수: %{customdata[0]}일"
        "<extra></extra>"
    )
)

fig4.update_layout(
    height=600,
    xaxis_title="기간 관객 수 (명)",
    yaxis_title="",
    xaxis_tickformat=",",
    margin=dict(
        l=20,
        r=120,
        t=40,
        b=20
    )
)

st.plotly_chart(
    fig4,
    use_container_width=True
)


