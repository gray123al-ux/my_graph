
# =========================================================
# 그래프 3. 날짜별 10위권 일관객 합계
# =========================================================

st.divider()

st.header("3. 날짜별 10위권 일관객 합계")

st.write(
    "각 날짜의 박스오피스 10위권 영화들의 일관객을 모두 더해 "
    "하루 전체 관객 규모의 변화를 살펴봅니다."
)


# ---------------------------------------------------------
# 날짜별 일관객 합계 계산
# ---------------------------------------------------------

daily_total = (
    df.groupby("날짜", as_index=False)["일관객"]
    .sum()
    .sort_values("날짜")
)


# ---------------------------------------------------------
# 가장 관객이 많았던 3일 찾기
# ---------------------------------------------------------

top3_days = (
    daily_total
    .nlargest(3, "일관객")
    .sort_values("날짜")
)


# ---------------------------------------------------------
# 영역 그래프
# ---------------------------------------------------------

fig3 = px.area(
    daily_total,
    x="날짜",
    y="일관객",
    labels={
        "날짜": "날짜",
        "일관객": "10위권 일관객 합계"
    }
)

fig3.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}"
        "<br>10위권 관객 합계: %{y:,.0f}명"
        "<extra></extra>"
    )
)


# ---------------------------------------------------------
# 상위 3일 표시
# ---------------------------------------------------------

fig3.add_scatter(
    x=top3_days["날짜"],
    y=top3_days["일관객"],
    mode="markers+text",
    text=[
        f"{date:%m/%d}"
        for date in top3_days["날짜"]
    ],
    textposition="top center",
    marker=dict(
        size=10
    ),
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}"
        "<br>10위권 관객 합계: %{y:,.0f}명"
        "<extra></extra>"
    ),
    showlegend=False
)


fig3.update_layout(
    height=550,
    hovermode="x unified",
    xaxis_title="날짜",
    yaxis_title="10위권 일관객 합계 (명)",
    yaxis_tickformat=",",
    margin=dict(
        l=20,
        r=20,
        t=60,
        b=20
    )
)


st.plotly_chart(
    fig3,
    use_container_width=True
)


# ---------------------------------------------------------
# TOP 3 날짜 간단히 표시
# ---------------------------------------------------------

st.subheader("🏆 관객이 가장 많았던 날")

for rank, row in enumerate(
    daily_total.nlargest(3, "일관객").itertuples(),
    start=1
):
    st.write(
        f"**{rank}위 — {row.날짜:%Y년 %m월 %d일}** "
        f": {row.일관객:,.0f}명"
    )


st.info(
    "💡 이 그래프로 알 수 있는 것: "
    "날짜별 10위권 전체 관객 규모의 변화를 볼 수 있고, 관객이 특히 많이 몰린 날을 확인할 수 있습니다."
)
